import { readFile, writeFile, mkdir } from "node:fs/promises";

const root = new URL("../", import.meta.url);
const read = async (name) =>
  JSON.parse(
    await readFile(new URL(`data/food-catalog/${name}.json`, root), "utf8"),
  );
const [recipes, ingredients, links, steps, vegetables, sources] =
  await Promise.all(
    [
      "recipes",
      "ingredients",
      "recipe_ingredients",
      "recipe_steps",
      "vegetables",
      "sources",
    ].map(read),
  );
const byId = (rows) => new Map(rows.map((row) => [row.id, row]));
const ingredientById = byId(ingredients);
const vegetableById = byId(vegetables);
const sourceById = byId(sources);
// 카탈로그의 bell-pepper는 B의 판매 카탈로그에서 paprika로 부른다.
const appVegetableId = (id) => (id === "bell-pepper" ? "paprika" : id);
const output = recipes.map((recipe) => {
  const recipeLinks = links
    .filter((link) => link.recipe_id === recipe.id)
    .sort((a, b) => a.position - b.position);
  const vegetableIds = [
    ...new Set(
      recipeLinks
        .map((link) => ingredientById.get(link.ingredient_id)?.vegetable_id)
        .filter(Boolean),
    ),
  ];
  // 말린 애호박(호박고지)을 생 애호박 판매 상품과 자동 연결하지 않는다.
  const productVegetableIds = [
    ...new Set(
      recipeLinks
        .filter((link) => link.form !== "dried")
        .map((link) => ingredientById.get(link.ingredient_id)?.vegetable_id)
        .filter(Boolean),
    ),
  ];
  const source = sourceById.get(recipe.source_id);
  if (!source || !/^https:\/\//.test(source.url))
    throw new Error(`Missing official source: ${recipe.id}`);
  return {
    id: `official-${recipe.id}`,
    name: recipe.title,
    description: recipe.description,
    cookTimeMin: recipe.cook_time_min,
    difficulty: recipe.difficulty,
    servings: recipe.servings,
    ingredients: recipeLinks.map((link) => ({
      name: link.source_name,
      amount: link.quantity_text ?? "수량 미기재",
    })),
    steps: steps
      .filter((step) => step.recipe_id === recipe.id)
      .sort((a, b) => a.position - b.position)
      .map((step) => step.instruction),
    vegetables: vegetableIds.map((id) => ({
      id: appVegetableId(id),
      name: vegetableById.get(id).name,
    })),
    productVegetableIds: productVegetableIds.map(appVegetableId),
    sourceUrl: source.url,
    sourceName: source.organization,
  };
});
await mkdir(new URL("src/data/generated/", root), { recursive: true });
await writeFile(
  new URL("src/data/generated/verified-recipes.json", root),
  `${JSON.stringify(output, null, 2)}\n`,
);
const quote = (text) => `'${String(text).replaceAll("'", "''")}'`;
const json = (value) => `${quote(JSON.stringify(value))}::jsonb`;
const number = (value) => (value == null ? "null" : String(value));
const values = output
  .map(
    (recipe) =>
      `(${[quote(recipe.id), quote(recipe.name), quote(recipe.description), number(recipe.cookTimeMin), recipe.difficulty == null ? "null" : quote(recipe.difficulty), number(recipe.servings), json(recipe.ingredients), json(recipe.steps), json(recipe.vegetables), quote(recipe.sourceUrl), quote(recipe.sourceName)].join(", ")})`,
  )
  .join(",\n");
const productLinks = output.flatMap((recipe) =>
  recipe.productVegetableIds.map((id) => `(${quote(recipe.id)}, ${quote(id)})`),
);
const sql = `-- Generated by node scripts/export-app-recipes.mjs; source: data/food-catalog.\n-- Apply 202610110001_verified_recipe_metadata.sql first.\n-- Updates official-* IDs only; existing example recipes and user data are preserved.\nbegin;\ninsert into public.recipes (id, name, description, cook_time_min, difficulty, servings, ingredients, steps, vegetables, source_url, source_name) values\n${values}\non conflict (id) do update set name=excluded.name, description=excluded.description, cook_time_min=excluded.cook_time_min, difficulty=excluded.difficulty, servings=excluded.servings, ingredients=excluded.ingredients, steps=excluded.steps, vegetables=excluded.vegetables, source_url=excluded.source_url, source_name=excluded.source_name;\n-- Reconcile only this catalog's links to the current active sales products.\ndelete from public.recipe_products where recipe_id in (${output.map((recipe) => quote(recipe.id)).join(", ")});\ninsert into public.recipe_products (recipe_id, product_id)\nselect distinct candidate.recipe_id, product.id from (values\n${productLinks.join(",\n")}\n) as candidate(recipe_id, vegetable_id)\njoin public.products product on product.vegetable_id = candidate.vegetable_id and product.is_active\non conflict do nothing;\ncommit;\n`;
await writeFile(new URL("supabase/seeds/verified-recipes.sql", root), sql);
console.log(
  `Exported ${output.length} official recipes; ${links.length} ingredient rows; ${steps.length} steps.`,
);
